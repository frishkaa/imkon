// map UI lang code -> backend language_pref
export const LANG_PREF: Record<Lang, string> = { en: "english", ru: "russian", tg: "tajik" };
export const LANG_LABEL: Record<Lang, string> = { en: "EN", ru: "Русский", tg: "Тоҷикӣ" };

export function pickLang(pref?: string): Lang {
  if (pref === "tajik" || pref === "tg") return "tg";
  if (pref === "english" || pref === "en") return "en";
  return "ru";
}
// for a tri-lingual {tj,ru,en} label from /meta
export function l3(lang: Lang, label: { tj: string; ru: string; en: string }): string {
  return lang === "tg" ? label.tj : lang === "en" ? label.en : label.ru;
}
